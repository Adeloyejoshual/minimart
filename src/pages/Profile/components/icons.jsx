/* ─────────────────────────────────────────────
   safeIc — never returns undefined
   Usage: const Icon = safeIc("Chart");  <Icon />
───────────────────────────────────────────── */
export const safeIc = (key) => {
  const icon = Ic[key];
  if (!icon) {
    console.warn(`[safeIc] Missing icon: "${key}"`);
    return Ic.Fallback;
  }
  return icon;
};