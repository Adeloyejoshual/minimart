export const getModelsByCategoryBrand = (category, brand) => models[category]?.[brand] ?? [];
export const getModelsByCategory = (category) => models[category] ?? {};
export const getAllCategories = () => Object.keys(models);
export const getAllBrandsInCategory = (category) => Object.keys(models[category] ?? {});
export const searchModels = (query) => {
  const results = [];
  for (const [category, brands] of Object.entries(models)) {
    for (const [brand, modelList] of Object.entries(brands)) {
      const matches = modelList.filter(model => model.toLowerCase().includes(query.toLowerCase()));
      if (matches.length > 0) results.push({ category, brand, models: matches });
    }
  }
  return results;
};